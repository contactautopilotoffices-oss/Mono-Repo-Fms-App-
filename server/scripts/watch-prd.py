    logger.info("")

    # Start watching
    event_handler = PRDFileHandler()
    observer = Observer()
    observer.schedule(event_handler, str(ACTIVE_PRD.parent), recursive=False)
    observer.start()

    logger.info("👀 Watching for PRD changes...")
    logger.info("Press Ctrl+C to stop.\n")

    try:
        while True:
            time.sleep(1)
    except KeyboardInterrupt:
        logger.info("\nStopping watcher...")
        observer.stop()

    observer.join()
    logger.info("Watcher stopped.")


